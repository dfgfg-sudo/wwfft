class Parser:
    @staticmethod
    def parse(text: str) -> Dict:
        s = text.strip()
        if s.startswith(('{','[')):
            try: return json.loads(s)
            except: pass
        if ':' in s and ('\\n' in s or '---' in s):
            try: return yaml.safe_load(s)
            except: pass
        if '=' in s and '\\n' in s:
            try: return toml.loads(s)
            except: pass
        res = {}
        for line in s.split('\\n'):
            if '=' in line:
                k,v = line.split('=',1)
                res[k.strip()] = v.strip()
        return res

