# 4. 使用示例
@Workflow-Factory 创建一个请假审批流程：
- 1-3天：经理审批
- 3-7天：经理 + HR 依次审批
- 7天以上：经理 + HR + CEO 依次审批
- 驳回则通知申请人
- 通过后同步到考勤系统

